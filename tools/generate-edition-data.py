#!/usr/bin/env python3
"""Generate site palette/default metadata from trusted repository sources (Python 3.11+).

Editorial text remains editable in edition.conf / make-editions.sh. This script
never sources edition.conf. Only the trusted runtime helper is sourced for its
base-default function; no user config or installed theme is read.
"""
import argparse
import colorsys
import hashlib
import json
from pathlib import Path
import re
import shlex
import subprocess
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def config(path):
    values = {}
    for line in path.read_text().splitlines():
        match = re.fullmatch(r'\s*([A-Z_]+)\s*=\s*(.*?)\s*', line)
        if match:
            words = shlex.split(match[2], comments=True)
            values[match[1]] = ' '.join(words)
    return values


def edition_data(source):
    script = (source / 'tools/make-editions.sh').read_text()
    specs = re.findall(r'^\s*"([a-z]+)\|([0-9.]+)\|[^"\n]+"\s*$', script, re.M)
    if not specs:
        raise ValueError('no edition specifications found')
    base_palette = tomllib.loads((source / 'colors.toml').read_text())
    base_hue = colorsys.rgb_to_hls(*(int(base_palette['accent'][i:i+2], 16) / 255 for i in (1, 3, 5)))[0] * 360
    keys = ['CURSOR_FX', 'ROTATE', 'DIM', 'GLOW_RANGE', 'EMBER_STYLE']
    # The helper defines functions only. Keep HOME isolated even if this changes.
    with tempfile.TemporaryDirectory() as home:
        proc = subprocess.run(['bash', '--noprofile', '--norc', '-c',
                               'source "$1"; shift; for key; do ab_base_default "$key" || exit; echo; done',
                               'metadata', str(source / 'extras/afterburn-theme.sh'), *keys],
                              env={'HOME': home, 'PATH': '/usr/bin:/bin'}, check=True, capture_output=True, text=True)
    defaults = dict(zip(keys, [line for line in proc.stdout.splitlines() if line]))
    if set(defaults) != set(keys):
        raise ValueError('base default interface returned incomplete values')
    base_text = config(source / 'tools/make-editions.sh')
    data = {}
    for name, target in [('afterburn', None), *specs]:
        colors_path = Path('colors.toml') if target is None else Path('.editions') / name / 'colors.toml'
        conf_path = Path('tools/make-editions.sh') if target is None else Path('tools/edition-extras') / name / 'edition.conf'
        colors = tomllib.loads((source / colors_path).read_text())
        conf = defaults | {'TAGLINE': base_text['BASE_TAGLINE'], 'PERSONALITY': base_text['BASE_PERSONALITY']} if target is None else config(source / conf_path)
        stops = re.findall(r'rgba\(([0-9a-fA-F]{6})[0-9a-fA-F]{2}\)', colors['hyprland_active_border'])
        if len(stops) != 3:
            raise ValueError(f'{colors_path}: expected three border stops')
        used = [colors_path, conf_path, Path('tools/make-editions.sh'), Path('extras/afterburn-theme.sh')]
        provenance = {'colors': colors_path.as_posix(), 'config': conf_path.as_posix(), 'sha256': {p.as_posix(): hashlib.sha256((source / p).read_bytes()).hexdigest() for p in sorted(set(used))}}
        row = {'name': name.title(), 'tag': conf['TAGLINE'], 'pers': conf['PERSONALITY'],
               's': ['#' + s.lower() for s in stops], 'rust': colors.get('afterburn_cool', colors['magenta']),
               'brown': colors['brown'], 'sel': colors['selection'], 'glow': int(conf['GLOW_RANGE']),
               'rot': {'off': 0, 'slow': 10, 'medium': 5, 'fast': 2.5}[conf['ROTATE']],
               'hue': 0 if target is None else round((float(target) - base_hue) % 360),
               'cursor': conf['CURSOR_FX'], 'dim': float(conf['DIM']), 'emberStyle': conf['EMBER_STYLE'],
               'provenance': provenance}
        # Strong foreground for low-lightness accents (currently Redline).
        lightness = colorsys.rgb_to_hls(*(int(row['s'][0][i:i+2], 16) / 255 for i in (1, 3, 5)))[1]
        if lightness < 0.5:
            row['on'] = colors['bright_foreground']
        data[name] = row
    return data


def javascript(data):
    return '// Generated by tools/generate-edition-data.py; do not edit.\nwindow.AFTERBURN_EDITIONS = ' + json.dumps(data, indent=2, ensure_ascii=True) + ';\n'


def markdown(data):
    lines = ['# Edition defaults', '',
             'Generated by `tools/generate-edition-data.py`; do not edit this table. Change the canonical edition config or runtime base defaults, then regenerate.', '',
             'These are edition defaults. Saved user settings take precedence; motion and saver policies can suspend effects without changing these choices.', '',
             '| Edition | Cursor effect | Rotation (seconds) | Dim | Glow range | Lock style |',
             '| --- | --- | ---: | ---: | ---: | --- |']
    for row in data.values():
        lines.append(f"| {row['name']} | {row['cursor']} | {row['rot']:g} | {row['dim']:g} | {row['glow']} | {row['emberStyle']} |")
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=ROOT)
    parser.add_argument('--output', type=Path, help='generated site JavaScript output')
    parser.add_argument('--markdown-output', type=Path, help='generated edition-defaults table')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    if not args.output and not args.markdown_output:
        parser.error('request --output and/or --markdown-output')
    try:
        data = edition_data(args.source.resolve())
        outputs = []
        if args.output:
            outputs.append((args.output, javascript(data)))
        if args.markdown_output:
            outputs.append((args.markdown_output, markdown(data)))
        for path, expected in outputs:
            if args.check:
                if not path.exists() or path.read_text() != expected:
                    parser.exit(1, f'edition metadata drift: regenerate {path}\n')
            else:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(expected)
    except (OSError, ValueError, KeyError, subprocess.CalledProcessError) as error:
        parser.exit(1, f'edition metadata: {error}\n')

if __name__ == '__main__':
    main()
