"""`afterburn apply` replaces hyprland.lua whole or not at all: Hyprland reloads on change."""
import unittest

from support import Sandbox


class WriteLua(unittest.TestCase):
    def setUp(self):
        self.sb = Sandbox()
        self.addCleanup(self.sb.cleanup)
        self.cur = self.sb.home / ".local/state/omarchy/current/theme"
        self.cur.mkdir(parents=True)
        self.lua = self.cur / "hyprland.lua"

    def test_apply_writes_the_file_and_leaves_no_temp_file(self):
        r = self.sb.afterburn("apply")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("generated by 'afterburn apply'", self.lua.read_text())
        self.assertEqual(sorted(p.name for p in self.cur.iterdir()), ["hyprland.lua"])
        self.assertEqual(self.lua.stat().st_mode & 0o777, 0o644)

    def test_a_failure_halfway_keeps_the_old_file_whole(self):
        self.lua.write_text("-- the old file\n")
        stub = self.sb.bin / "sed"
        stub.unlink()                       # it is a symlink to the real sed: never write through it
        stub.write_text("#!/bin/bash\nexit 1\n")   # the glow recolour step fails
        stub.chmod(0o755)
        r = self.sb.afterburn("apply")
        self.assertNotEqual(r.returncode, 0)
        self.assertIn("old file is untouched", r.stderr)
        self.assertEqual(self.lua.read_text(), "-- the old file\n")
        self.assertEqual(sorted(p.name for p in self.cur.iterdir()), ["hyprland.lua"])


if __name__ == "__main__":
    unittest.main()
