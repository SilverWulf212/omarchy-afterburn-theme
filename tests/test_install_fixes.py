class LocateLocaleTests(unittest.TestCase):
    def test_locate_formats_lat_lon_with_a_dot_under_a_comma_locale(self):
        sb = Sandbox()
        self.addCleanup(sb.cleanup)
        # No comma-decimal locale is installed system-wide, so compile de_DE into the sandbox and point LOCPATH at it.
        loc = sb.root / "locales"
        loc.mkdir()
        built = subprocess.run(["localedef", "-i", "de_DE", "-f", "UTF-8", str(loc / "de_DE.UTF-8")],
                               capture_output=True, text=True) if shutil.which("localedef") else None
        if built is None or not (loc / "de_DE.UTF-8" / "LC_NUMERIC").exists():
            self.skipTest("cannot build a de_DE locale here")
        # The ZIP lookup is faked: curl is not one of the sandbox tools.
        curl = sb.bin / "curl"
        curl.write_text('#!/bin/bash\necho \'{"places":[{"latitude":"34.0901","longitude":"-118.4065"}]}\'\n')
        curl.chmod(0o755)
        r = sb.afterburn("locate", "90210", LOCPATH=str(loc), LC_ALL="de_DE.UTF-8")
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("LAT 34.0901, LON -118.4065", r.stdout)


class HookRunsOnlyOurCli(unittest.TestCase):  # Codex review C7
    def setUp(self):
        from support import REPO
        self.hook = REPO / "extras" / "afterburn-theme-set-hook"
        self.repo = REPO
        self.sb = Sandbox()
        self.addCleanup(self.sb.cleanup)
        self.sb.use_stubs(["afterburn"])   # someone else's `afterburn` on PATH

    def run_hook(self):
        r = self.sb.run(["/bin/bash", str(self.hook), "afterburn"])
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)

    def test_a_foreign_afterburn_on_path_is_never_run(self):
        self.run_hook()
        self.assertFalse([c for c in self.sb.call_log() if c.startswith("afterburn ")], self.sb.call_log())

    def test_our_link_in_local_bin_is_run(self):
        b = self.sb.home / ".local/bin"
        b.mkdir(parents=True)
        (b / "afterburn").symlink_to(self.repo / "extras" / "bin" / "afterburn")
        (self.sb.home / ".local/state/omarchy/current/theme").mkdir(parents=True)
        self.run_hook()
        self.assertFalse([c for c in self.sb.call_log() if c.startswith("afterburn ")])
        self.assertIn("generated by 'afterburn apply'",
                      (self.sb.home / ".local/state/omarchy/current/theme/hyprland.lua").read_text())


class InstallRecordsWhatItChanges(unittest.TestCase):
    def setUp(self):
        self.sb = Sandbox()
        self.addCleanup(self.sb.cleanup)

    def test_a_fresh_user_without_a_terminal_list_is_recorded_as_none(self):
        r = self.sb.install()
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertEqual((self.sb.state_dir / "prev-terminal").read_text().strip(), "none")

    def test_the_users_own_terminal_list_is_recorded(self):
        self.sb.write_state_text(self.sb.home / ".config" / "xdg-terminals.list", "# mine\nfoot.desktop\n")
        self.sb.install()
        self.assertEqual((self.sb.state_dir / "prev-terminal").read_text().strip(), "foot.desktop")

    def test_a_list_with_only_comments_and_blanks_is_recorded_as_none(self):
        self.sb.write_state_text(self.sb.home / ".config" / "xdg-terminals.list", "# nothing yet\n\n")
        self.sb.install()
        self.assertEqual((self.sb.state_dir / "prev-terminal").read_text().strip(), "none")

    def test_a_running_watcher_is_restarted_so_new_code_takes_effect(self):
        self.sb.install(STUB_WATCHER="active")
        calls = self.sb.call_log()
        enable = calls.index("systemctl --user enable --now afterburn-watch.service")
        self.assertIn("systemctl --user restart afterburn-watch.service", calls[enable:])

    def test_a_watcher_that_was_not_running_is_only_started(self):
        self.sb.install(STUB_WATCHER="inactive")
        self.assertFalse([c for c in self.sb.call_log() if " restart " in c], self.sb.call_log())


class CursorFxDownloadFailureTests(unittest.TestCase):
    def setUp(self):
        self.sb = Sandbox()
        self.addCleanup(self.sb.cleanup)
        (self.sb.bin / "cursor-fx").unlink()
        git = self.sb.bin / "git"
        git.write_text(r'''#!/bin/bash
echo "git $*" >> "$SB/calls.log"
if [[ $1 == clone ]]; then
  [[ ${STUB_GIT_FAIL:-} != clone ]] || exit 128
  mkdir -p "${@: -1}"
  exit 0
fi
[[ ${STUB_GIT_FAIL:-} != checkout ]] || exit 128
''')
        git.chmod(0o755)

    def assert_other_extras_finish(self, failure):
        r = self.sb.install(STUB_GIT_FAIL=failure)
        self.assertEqual(r.returncode, 0, r.stdout + r.stderr)
        self.assertIn("couldn't download the tested cursor-fx version; the rest of the install will continue", r.stdout)
        self.assertTrue(any(c.startswith("omarchy hook install theme-set ") for c in self.sb.call_log()),
                        self.sb.call_log())
        self.assertIn("omarchy theme set afterburn", self.sb.call_log())
        self.assertFalse((self.sb.home / ".local/share/afterburn/ghostty-cursor-fx").exists())
        self.assertNotIn("cursor-fx installed", r.stdout)

    def test_a_clone_failure_does_not_stop_the_rest_of_the_installer(self):
        self.assert_other_extras_finish("clone")

    def test_a_missing_pinned_commit_does_not_stop_the_rest_of_the_installer(self):
        self.assert_other_extras_finish("checkout")


if __name__ == "__main__":
    unittest.main()
